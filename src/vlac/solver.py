    def solve_bare_modes(
        self,
        geometry: CrossSectionGeometry,
        wavelength_m: float,
        *,
        references: tuple[BareModeReference, ...] = (),
        mesh_accuracy: int | None = None,
    ) -> BareModes:
        reference_fingerprints = tuple(ref.fingerprint() for ref in references)
        bare_key = stable_key(
            {
                "kind": "bare_modes_full_width_slabs_explicit_xy_v23",
                "selection": self._selection_signature(),
                "geometry": geometry.__dict__,
                "wavelength_m": float(wavelength_m),
                "mesh_accuracy_level": (
                    self.mesh_accuracy if mesh_accuracy is None else mesh_accuracy
                ),
                "mesh_cells": self._mesh_cell_counts(mesh_accuracy),
                "references": reference_fingerprints,
                "trial_modes": self.config.solver.number_of_trial_modes,
                "domain_m": [self.x_span_m, self.y_min_m, self.y_max_m],
                "materials": self._material_signature(),
            }
        )
        if self.cache:
            hit = self.cache.get(bare_key, kind="bare_modes")
            if hit is not None:
                return hit
        previous = tuple(
            ModeReference(
                upper=ref.upper,
                lower=ref.lower,
                supermodes=(ref.upper, ref.lower),
            )
            for ref in references
        )
        # For isolated modes, the other guide's SiN is omitted while the shared
        # oxide/liquid background regions remain. The bottom half-space is silica.
        upper_modes = self._raw_mode_candidates(
            geometry,
            wavelength_m,
            include_upper=True,
            include_lower=False,
            mesh_accuracy=mesh_accuracy,
        )
        upper, upper_overlap = select_mode(
            upper_modes,
            previous=previous,
            guide="upper",
            minimum_te_fraction=self.config.solver.minimum_te_fraction,
        )
        lower_modes = self._raw_mode_candidates(
            geometry,
            wavelength_m,
            include_upper=False,
            include_lower=True,
            mesh_accuracy=mesh_accuracy,
        )
        lower, lower_overlap = select_mode(
            lower_modes,
            previous=previous,
            guide="lower",
            minimum_te_fraction=self.config.solver.minimum_te_fraction,
        )
        scale = 2 * np.pi / wavelength_m
        result = BareModes(
            beta_upper=scale * upper.neff,
            beta_lower=scale * lower.neff,
            reference=BareModeReference(upper, lower),
            upper_tracking_overlap=upper_overlap,
            lower_tracking_overlap=lower_overlap,
        )
        if self.cache:
            self.cache.put(bare_key, result, kind="bare_modes")
        return result

    def evaluate_coefficients(
        self,
        geometry: CrossSectionGeometry,
        wavelength_m: float,
        *,
        references: tuple[ModeReference, ...] = (),
        previous_kappa: complex | None = None,
    ) -> tuple[Coefficients, ModeReference]:
        key = self._cache_identity(
            geometry,
            wavelength_m,
            reference_fingerprints=(r.fingerprint() for r in references),
            previous_kappa=previous_kappa,
        )
        if self.cache:
            hit = self.cache.get(key, kind="coefficients")
            if hit is not None:
                return hit

        previous_bare = tuple(
            BareModeReference(r.upper, r.lower) for r in references
        )
        bare = self.solve_bare_modes(
            geometry, wavelength_m, references=previous_bare
        )
        coupled_modes = self._raw_mode_candidates(
            geometry,
            wavelength_m,
            include_upper=True,
            include_lower=True,
        )
        plus, minus, super_overlap = select_supermode_pair(
            coupled_modes,
            bare.reference.upper,
            bare.reference.lower,
            previous=references,
            minimum_te_fraction=self.config.solver.minimum_te_fraction,
        )
        beta_scale = 2 * np.pi / wavelength_m
        beta_plus = beta_scale * plus.neff
        beta_minus = beta_scale * minus.neff
        delta_pm = (beta_plus - beta_minus) / 2
        overlap_ul = field_overlap(bare.reference.upper, bare.reference.lower)
        uo = field_overlap(plus, bare.reference.upper) ** 2
        lo = field_overlap(plus, bare.reference.lower) ** 2
        total = uo + lo
        profile_check = float("nan")
        if (
            total > 0
            and overlap_ul
            <= self.config.solver.field_overlap_crosscheck_max_basis_overlap
        ):
            uo, lo = uo / total, lo / total
            profile_check = float(abs(delta_pm) * 2 * np.sqrt(uo * lo))
        coefficients = extract_coupling(
            bare.beta_upper,
            bare.beta_lower,
            beta_plus,
            beta_minus,
            previous_kappa=previous_kappa,
            kappa_profile_check=profile_check,
            overlap_upper_lower=overlap_ul,
            min_mode_overlap=min(
                bare.upper_tracking_overlap,
                bare.lower_tracking_overlap,
                super_overlap,
            ),
            identities=(
                bare.reference.upper.identity,
                bare.reference.lower.identity,
                plus.identity,
                minus.identity,
            ),
        )
        if (
            coefficients.min_mode_overlap
            < self.config.solver.minimum_mode_overlap
        ):
            coefficients.extraction_flag = "low_mode_overlap"
        reference = ModeReference(
            bare.reference.upper,
            bare.reference.lower,
            (plus, minus),
        )
        result = (coefficients, reference)
        if self.cache:
            self.cache.put(key, result, kind="coefficients")
        return result

    def mesh_domain_convergence(
        self,
        geometry: CrossSectionGeometry,
        wavelength_m: float,
        *,
        progress=None,
    ) -> list[dict]:
        """Repeat one section at configured mesh accuracies, reporting deltas."""
        rows = []
        previous = None
        if progress:
            progress.start_stage(
                "FDE mesh convergence",
                total=len(self.config.solver.mesh_accuracy_refinements),
                unit="mesh levels",
            )
        for accuracy in self.config.solver.mesh_accuracy_refinements:
            bare = self.solve_bare_modes(
                geometry, wavelength_m, mesh_accuracy=accuracy
            )
            coupled = self._raw_mode_candidates(
                geometry,
                wavelength_m,
                include_upper=True,
                include_lower=True,
                mesh_accuracy=accuracy,
            )
            plus, minus, _ = select_supermode_pair(
                coupled,
                bare.reference.upper,
                bare.reference.lower,
                minimum_te_fraction=self.config.solver.minimum_te_fraction,
            )
            factor = 2 * np.pi / wavelength_m
            beta_plus, beta_minus = factor * plus.neff, factor * minus.neff
            kappa = np.sqrt(
                ((beta_plus - beta_minus) / 2) ** 2
                - ((bare.beta_upper - bare.beta_lower) / 2) ** 2
                + 0j
            )
            current = {
                "mesh_accuracy": accuracy,
                "mesh_cells_x": self._mesh_cell_counts(accuracy)[0],
                "mesh_cells_y": self._mesh_cell_counts(accuracy)[1],
                "neff_upper": (bare.beta_upper * wavelength_m / (2 * np.pi)),
                "neff_lower": (bare.beta_lower * wavelength_m / (2 * np.pi)),
                "delta_beta_rad_per_m": bare.beta_upper - bare.beta_lower,
                "kappa_rad_per_m": kappa,
            }
            if previous is not None:
                current["delta_neff_upper_from_previous"] = abs(
                    current["neff_upper"] - previous["neff_upper"]
                )
                current["delta_neff_lower_from_previous"] = abs(
                    current["neff_lower"] - previous["neff_lower"]
                )
                current["relative_kappa_change"] = abs(
                    kappa - previous["kappa_rad_per_m"]
                ) / max(abs(kappa), abs(previous["kappa_rad_per_m"]), 1e-30)
            rows.append(current)
            previous = current
            if progress:
                progress.update(
                    len(rows),
                    detail=f"mesh {current['mesh_cells_x']} x {current['mesh_cells_y']} cells",
                )
        if progress:
            progress.finish_stage()
        return rows

    def domain_convergence(
        self,
        geometry: CrossSectionGeometry,
        wavelength_m: float,
        *,
        scales: list[float] | None = None,
        progress=None,
    ) -> list[dict]:
        """Repeat one section with larger lateral, top and bottom-oxide domains."""
        scales = scales or self.config.solver.domain_scale_factors
        if not scales or min(scales) < 1.0 or sorted(scales) != scales:
            raise ValueError("Domain scale factors must be ordered and start at >= 1.")
        original = (self.x_span_m, self.y_min_m, self.y_max_m, self.track_x, self.track_y)
        rows = []
        previous = None
        completed_ok = False
        if progress:
            progress.start_stage(
                "FDE domain convergence", total=len(scales), unit="domain sizes"
            )
        try:
            for scale in scales:
                self._build_domain(scale)
                bare = self.solve_bare_modes(geometry, wavelength_m)
                coupled = self._raw_mode_candidates(
                    geometry,
                    wavelength_m,
                    include_upper=True,
                    include_lower=True,
                )
                plus, minus, _ = select_supermode_pair(
                    coupled,
                    bare.reference.upper,
                    bare.reference.lower,
                    minimum_te_fraction=self.config.solver.minimum_te_fraction,
                )
                factor = 2 * np.pi / wavelength_m
                bp, bm = factor * plus.neff, factor * minus.neff
                kp = np.sqrt(
                    ((bp - bm) / 2) ** 2
                    - ((bare.beta_upper - bare.beta_lower) / 2) ** 2
                    + 0j
                )
                current = {
                    "domain_scale": float(scale),
                    "x_span_m": self.x_span_m,
                    "y_min_m": self.y_min_m,
                    "y_max_m": self.y_max_m,
                    "neff_upper": bare.beta_upper / factor,
                    "neff_lower": bare.beta_lower / factor,
                    "delta_beta_rad_per_m": bare.beta_upper - bare.beta_lower,
                    "kappa_rad_per_m": kp,
                }
                if previous is not None:
                    current["delta_neff_upper_from_previous"] = abs(
                        current["neff_upper"] - previous["neff_upper"]
                    )
                    current["delta_neff_lower_from_previous"] = abs(
                        current["neff_lower"] - previous["neff_lower"]
                    )
                    current["relative_kappa_change"] = abs(
                        kp - previous["kappa_rad_per_m"]
                    ) / max(abs(kp), abs(previous["kappa_rad_per_m"]), 1e-30)
                rows.append(current)
                previous = current
                if progress:
                    progress.update(
                        len(rows),
                        detail=f"domain scale {scale:g}x",
                    )
            completed_ok = True
        finally:
            self.x_span_m, self.y_min_m, self.y_max_m, self.track_x, self.track_y = original
            if progress and completed_ok:
                progress.finish_stage()
        return rows
