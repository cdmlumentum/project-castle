class LumapiUnavailable(RuntimeError):
    pass


class LumapiBackend:
    """Build each local cross-section and solve its isolated and coupled modes."""

    backend_name = "ansys_lumerical_mode_fde"

    def __init__(
        self,
        config: WorkflowConfig,
        *,
        cache_path: str | Path | None = None,
        mesh_accuracy: int | None = None,
        progress=None,
    ):
        self.config = config
        self.config.validate()
        self.bank = build_material_bank(config)
        self.mesh_accuracy = (
            config.solver.mesh_accuracy if mesh_accuracy is None else mesh_accuracy
        )
        self.progress = progress
        self.cache = SQLiteCache(cache_path, progress=progress, max_bytes=config.output.cache_max_bytes) if cache_path else None
        self._session = None
        self._preflight_wavelength = None
        self.budget = RunBudget(config.execution)
        self._closed = False
        self._project_ready = False
        self._installed_material_names = set()
        self._raw_memory = OrderedDict()
        self.performance_stats = {}
        self._build_domain()

    @property
    def session(self):
        """Acquire a license only when a cache miss needs MODE."""
        if getattr(self, '_session', None) is None:
            self._lumapi = self._import_lumapi()
            self._session = self._open_session()
            wavelength = getattr(self, '_preflight_wavelength', None)
            self._preflight_wavelength = None
            try:
                if wavelength is not None:
                    self.preflight(wavelength)
            except BaseException:
                self.close()
                raise
        return self._session

    @session.setter
    def session(self, value):
        self._session = value

    def _budget(self):
        if not hasattr(self, 'budget'):
            self.budget = RunBudget(self.config.execution)
        return self.budget

    def _mesh_cell_counts(self, mesh_level: int | None = None) -> tuple[int, int]:
        """Map the configured refinement level to native MODE FDE mesh cells."""
        level = self.mesh_accuracy if mesh_level is None else mesh_level
        factor = 2.0 ** (level - self.config.solver.mesh_accuracy)
        if self.config.solver.calibration:
            from .block0 import certified_profile
            profile = certified_profile(self.config, 'coupled')
            return max(2, round(profile.nx*factor)), max(2, round(profile.ny*factor))
        return (
            max(2, int(round(self.config.solver.mesh_cells_x * factor))),
            max(2, int(round(self.config.solver.mesh_cells_y * factor))),
        )

    def _import_lumapi(self):
        raw = self.config.solver.api_path or os.environ.get("LUMERICAL_PYTHON_API")
        if raw:
            api_path = Path(raw).expanduser().resolve()
            if api_path.is_file():
                if api_path.name.lower() != "lumapi.py":
                    raise LumapiUnavailable(
                        "Lumerical API file path must point to lumapi.py; got "
                        f"{api_path}"
                    )
                sys.path.insert(0, str(api_path.parent))
            elif api_path.is_dir():
                if not (api_path / "lumapi.py").is_file():
                    raise LumapiUnavailable(
                        f"Lumerical API path does not contain lumapi.py: {api_path}"
                    )
                sys.path.insert(0, str(api_path))
            else:
                raise LumapiUnavailable(
                    f"Lumerical API path does not exist: {api_path}. Set "
                    "solver.api_path or LUMERICAL_PYTHON_API to the folder "
                    "containing lumapi.py."
                )
        try:
            return importlib.import_module("lumapi")
        except Exception as exc:
            raise LumapiUnavailable(
                "Ansys Lumerical lumapi could not be imported. Install/activate "
                "Lumerical MODE, then set solver.api_path or "
                "LUMERICAL_PYTHON_API to the directory containing lumapi.py."
            ) from exc

    def _open_session(self):
        args = {"threads": str(self.config.solver.threads)}
        # Lumerical's -hide option selects the offscreen Qt platform itself.
        # Only pass the visible-window platform when the GUI is requested.
        if self.config.solver.platform and not self.config.solver.hide_gui:
            args["platform"] = self.config.solver.platform
        try:
            return self._lumapi.MODE(
                hide=self.config.solver.hide_gui,
                serverArgs=args,
            )
        except Exception as exc:
            raise LumapiUnavailable(
                "Could not start an Ansys Lumerical MODE session. Check the "
                "installation, MODE license, and serverArgs in the configuration."
            ) from exc

    def preflight(self, wavelength_m: float) -> None:
        """Run a tiny empty-domain eigenmode solve to check the FDE license path."""
        if getattr(self, '_session', None) is None:
            self._preflight_wavelength = wavelength_m
            return
        self._budget().check(1)
        self._budget().consume(1)
        script = f"""
            newproject;
            addfde;
            set("solver type",3);
            set("z",0);
            set("x",0);
            set("x span",2e-6);
            set("y",0);
            set("y span",2e-6);
            setanalysis("wavelength",{wavelength_m:.15g});
            findmodes;
        """
        self._project_ready = False
        self._installed_material_names = set()
        solve_token = self.progress.solver_started() if self.progress else None
        try:
            self.session.eval(script)
        except Exception as exc:
            if self.progress and solve_token is not None:
                self.progress.solver_finished(solve_token, error=str(exc))
            raise LumapiUnavailable(
                "MODE launched, but the small FDE preflight solve failed. Check "
                "the MODE/FDE license and the Script Prompt error."
            ) from exc
        else:
            if self.progress and solve_token is not None:
                self.progress.solver_finished(solve_token)

    def _build_domain(self, scale: float = 1.0) -> None:
        g = self.config.geometry
        s = self.config.solver
        self.x_span_m = scale * 2 * (
            max(abs(g.d_c2c_bounds_m[0]), abs(g.d_c2c_bounds_m[1]))
            + max(g.w1_max_m, g.w1_lower_m) / 2
            + g.domain_margin_x_m
        )
        self.y_min_m = (
            -g.box_thickness_m
            - scale * s.domain_margin_y_bottom_m
        )
        self.y_max_m = (
            g.h_wg_m
            + g.h_gap_bounds_m[1]
            + g.h_wg_m
            + scale * g.domain_margin_top_m
        )
        if s.calibration:
            from .block0 import certified_profile
            profile = certified_profile(self.config, 'coupled')
            self.x_span_m = profile.x_span_m*scale
            self.y_min_m = profile.y_min_m
            self.y_max_m = profile.y_max_m
        self.track_x = np.linspace(
            -self.x_span_m / 2, self.x_span_m / 2, s.tracking_grid_nx
        )
        self.track_y = np.linspace(self.y_min_m, self.y_max_m, s.tracking_grid_ny)
        if s.calibration:
            self.track_x, self.track_y = profile.grid()

    def reconfigure(self, config: WorkflowConfig) -> None:
        """Apply a validated config update before starting a new solve block.

        Rebuild the domain and field grid to match the new configuration.
        """
        config.validate()
        self.config = config
        self.bank = build_material_bank(config)
        self._project_ready = False
        self._raw_memory = OrderedDict()
        self._build_domain()

    def _configured_full_x_span(self) -> float:
        g = self.config.geometry
        return 2 * (
            max(abs(g.d_c2c_bounds_m[0]), abs(g.d_c2c_bounds_m[1]))
            + max(g.w1_max_m, g.w1_lower_m) / 2
            + g.domain_margin_x_m
        )

    def endpoint_isolated_domain_info(
        self, *, compact_x: bool | None = None, mesh_accuracy: int | None = None
    ) -> dict:
        """Describe the endpoint-only domain and its resolution.

        The vertical material stack and y boundaries stay identical to the
        coupled-mode domain. Compact mode calculation removes only the
        translation allowance in x; it does not truncate the oxide or liquid
        regions. The bottom boundary lies in silica; no silicon substrate is
        present in this model.
        """
        compact = (
            self.config.solver.endpoint_compact_x
            if compact_x is None
            else bool(compact_x)
        )
        if compact and self.config.solver.calibration:
            from .block0 import certified_profile
            p = certified_profile(self.config, 'isolated')
            factor = 2. ** ((self.mesh_accuracy if mesh_accuracy is None else mesh_accuracy)-self.config.solver.mesh_accuracy)
            nx, ny = max(2, round(p.nx*factor)), max(2, round(p.ny*factor))
            return {'coordinate_frame': 'guide_centered', 'compact_x_enabled': True,
                    'x_span_m': p.x_span_m, 'y_min_m': p.y_min_m, 'y_max_m': p.y_max_m,
                    'y_span_m': p.y_max_m-p.y_min_m, 'mesh_cells_x': nx, 'mesh_cells_y': ny,
                    'full_domain_x_span_m': self.x_span_m, 'full_domain_mesh_cells_x': self._mesh_cell_counts(mesh_accuracy)[0],
                    'nominal_dx_m': p.x_span_m/nx, 'nominal_dy_m': (p.y_max_m-p.y_min_m)/ny,
                    'vertical_domain_policy': 'block0_certified',
                    'block0_certificate_id': self.config.solver.calibration['certificate_id']}
        full_x = self._configured_full_x_span()
        if compact:
            g = self.config.geometry
            x_span = 2 * (
                max(g.w1_max_m, g.w1_lower_m) / 2
                + g.domain_margin_x_m
            )
        else:
            x_span = self.x_span_m
        full_nx, cells_y = self._mesh_cell_counts(mesh_accuracy)
        cells_x = (
            max(2, int(round(full_nx * x_span / full_x)))
            if compact
            else full_nx
        )
        return {
            "coordinate_frame": "guide_centered" if compact else "full_device_cross_section",
            "compact_x_enabled": compact,
            "x_span_m": float(x_span),
            "y_min_m": float(self.y_min_m),
            "y_max_m": float(self.y_max_m),
            "y_span_m": float(self.y_max_m - self.y_min_m),
            "mesh_cells_x": int(cells_x),
            "mesh_cells_y": int(cells_y),
            "full_domain_x_span_m": float(full_x),
            "full_domain_mesh_cells_x": int(full_nx),
            "nominal_dx_m": float(x_span / cells_x),
            "nominal_dy_m": float((self.y_max_m - self.y_min_m) / cells_y),
            "vertical_domain_policy": "unchanged_from_coupled_mode_domain",
        }

    @contextmanager
    def _temporary_domain(
        self, *, x_span_m: float, y_min_m: float, y_max_m: float, profile=None
    ) -> Iterator[None]:
        """Temporarily set the field interpolation grid for one FDE solve."""
        previous = (
            self.x_span_m,
            self.y_min_m,
            self.y_max_m,
            self.track_x,
            self.track_y,
        )
        settings = self.config.solver
        self.x_span_m = float(x_span_m)
        self.y_min_m = float(y_min_m)
        self.y_max_m = float(y_max_m)
        self.track_x = np.linspace(
            -self.x_span_m / 2,
            self.x_span_m / 2,
            settings.tracking_grid_nx,
        )
        self.track_y = np.linspace(
            self.y_min_m, self.y_max_m, settings.tracking_grid_ny
        )
        old_profile = getattr(self, '_active_numerical_profile', None)
        self._active_numerical_profile = profile
        if profile is not None:
            self.track_x, self.track_y = profile.grid()
        try:
            yield
        finally:
            (
                self.x_span_m,
                self.y_min_m,
                self.y_max_m,
                self.track_x,
                self.track_y,
            ) = previous
            self._active_numerical_profile = old_profile

    def close(self) -> None:
        if not self._closed:
            try:
                if self._session is not None:
                    self._session.close()
            finally:
                self._closed = True

    def __enter__(self) -> "LumapiBackend":
        return self

    def __exit__(self, exc_type, exc, tb) -> None:
        # Optional diagnostic pause keeps the live MODE session available while
        # the user inspects its Script Prompt after any workflow exception.
        if (
            exc_type is not None
            and os.environ.get("VLAC_PAUSE_ON_MODE_ERROR", "").lower()
            in {"1", "true", "yes"}
        ):
            print(
                "MODE session is being kept open for inspection. Check the MODE "
                "Script Prompt and the dumped FDE script, then press Enter here "
                "to close MODE."
            )
            try:
                input()
            except EOFError:
                pass
        self.close()

    def _wavelength_samples_for_materials(self) -> np.ndarray:
        d = self.config.device
        return np.linspace(d.wavelength_min_m, d.wavelength_max_m, 81)

    @contextmanager
    def _timed(self, category: str):
        started = time.perf_counter()
        try:
            yield
        finally:
            seconds = time.perf_counter() - started
            if not hasattr(self, "performance_stats"):
                self.performance_stats = {}
            row = self.performance_stats.setdefault(category, {"calls": 0, "seconds": 0.0})
            row["calls"] += 1
            row["seconds"] += seconds
            if self.progress:
                self.progress.record_timing(category, seconds)

    def _install_materials(self, liquid_index: float) -> str:
        """Install static materials once and each distinct liquid index once."""
        if not hasattr(self, "_installed_material_names"):
            self._installed_material_names = set()
        liquid_name = "VLAC_Liquid_" + stable_key({"n": float(liquid_index)})[:12]
        wavelengths = self._wavelength_samples_for_materials()
        models = (
            ("SiO2_Malitson_1965", lambda: material_samples(self.bank.silica, wavelengths)),
            ("Si3N4_Luke_2015_provisional", lambda: material_samples(self.bank.sin, wavelengths)),
            (liquid_name, lambda: liquid_samples(type(self.bank.liquid_cross)(liquid_index), wavelengths)),
        )
        with self._timed("material_setup"):
            for index, (name, samples) in enumerate(models):
                if name in self._installed_material_names:
                    continue
                variable = f"vlac_material_data_{index}"
                self.session.putv(variable, np.asarray(samples(), dtype=complex))
                self.session.eval(
                    'tmp_mat = addmaterial("Sampled data");\n'
                    f'setmaterial(tmp_mat,"name","{name}");\n'
                    f'setmaterial("{name}","max coefficients",{self.config.materials.material_fit_max_coefficients});\n'
                    f'setmaterial("{name}","sampled data",{variable});\n'
                )
                self._installed_material_names.add(name)
        return liquid_name

    def _core_fraction(
        self,
        ex: np.ndarray,
        ey: np.ndarray,
        geometry: CrossSectionGeometry,
        guide: str,
    ) -> float:
        if guide == "upper":
            xc = geometry.d_c2c_m
            width = geometry.w1_m
            y0 = geometry.upper_bottom_y_m
        else:
            xc = 0.0
            width = geometry.w2_m
            y0 = geometry.lower_bottom_y_m
        xx, yy = np.meshgrid(self.track_x, self.track_y, indexing="ij")
        mask = (
            (np.abs(xx - xc) <= width / 2)
            & (yy >= y0)
            & (yy <= y0 + geometry.h_wg_m)
        )
        intensity = np.abs(ex) ** 2 + np.abs(ey) ** 2
        denom = float(np.sum(intensity))
        return 0.0 if denom == 0 else float(np.sum(intensity[mask]) / denom)

    def _to_common_grid(self, x: np.ndarray, y: np.ndarray, field: np.ndarray) -> np.ndarray:
        x = np.asarray(x).squeeze().astype(float)
        y = np.asarray(y).squeeze().astype(float)
        field = np.asarray(field).squeeze().astype(complex)
        if x.ndim != 1 or y.ndim != 1:
            raise RuntimeError("FDE field coordinates are not one-dimensional.")
        expected = (len(x), len(y))
        if field.shape == (len(y), len(x)):
            field = field.T
        if field.shape != expected:
            raise RuntimeError(
                "FDE field grid/component shapes differ from the returned x,y "
                f"coordinates: field={field.shape}, expected={expected}. "
                "Review the MODE API version's getdata expansion behavior."
            )
        if x[0] > x[-1]:
            x, field = x[::-1], field[::-1, :]
        if y[0] > y[-1]:
            y, field = y[::-1], field[:, ::-1]
        interp = RegularGridInterpolator(
            (x, y), field, bounds_error=False, fill_value=0j
        )
        xx, yy = np.meshgrid(self.track_x, self.track_y, indexing="ij")
        sampled = interp(np.column_stack((xx.ravel(), yy.ravel()))).reshape(
            xx.shape
        )
        return sampled

    @staticmethod
    def _scalar_complex(value) -> complex:
        arr = np.asarray(value).squeeze()
        if arr.size != 1:
            raise RuntimeError(f"Expected scalar effective index, got shape {arr.shape}.")
        return complex(arr.item())

    def _active_rectangles(self, geometry, include_upper, include_lower):
        return [rect for rect in rectangles_for_cross_section(
            geometry, x_span_m=self.x_span_m, y_min_m=self.y_min_m, y_max_m=self.y_max_m
        ) if not ((rect.name.startswith("upper_") and rect.name != "upper_liquid_cladding" and not include_upper)
                  or (rect.name.startswith("lower_") and not include_lower))]

    def _raw_mode_candidates(self, geometry, wavelength_m, *, include_upper, include_lower,
                             mesh_accuracy=None, mesh_cells_override=None, use_cache=True):
        """Cache the physical eigenproblem, independent of tracking references."""
        cells = self._mesh_cell_counts(mesh_accuracy) if mesh_cells_override is None else mesh_cells_override
        rects = self._active_rectangles(geometry, include_upper, include_lower)
        key = stable_key({
            "provenance": optical_identity(self.config),
            "kind": "raw_eigenmodes_explicit_xy_v23", "rectangles": [asdict(r) for r in rects],
            "liquid_index": float(geometry.liquid_index), "wavelength_m": float(wavelength_m),
            "domain_m": [self.x_span_m, self.y_min_m, self.y_max_m],
            "mesh_cells": list(cells), "trial_modes": self.config.solver.number_of_trial_modes,
            "tracking_grid": [self.config.solver.tracking_grid_nx, self.config.solver.tracking_grid_ny],
            "materials": self._material_signature(),
            "block0_profile": self._numerical_profile_identity(),
        })
        if not hasattr(self, "_raw_memory"):
            self._raw_memory = OrderedDict()
        if use_cache and key in self._raw_memory:
            remembered = self._raw_memory.pop(key)
            if remembered:
                self._raw_memory[key] = remembered
                if self.progress: self.progress.cache_event("raw_modes_memory", "hit")
                return remembered
        candidates = self.cache.get(key, kind="raw_modes") if self.cache and use_cache else None
        if candidates is not None and not candidates:
            # Older versions persisted []. It must not suppress a fresh solve.
            self.cache.delete(key)
            candidates = None
            if self.progress: self.progress.note("Ignored an empty cached mode list; running FDE again.",force=True)
        if candidates is None:
            recovered_from_zero = False
            for attempt in range(self.config.solver.zero_mode_retries+1):
                if attempt:
                    self._project_ready = False
                    if self.progress:
                        self.progress.note("FDE returned zero modes; retrying in a clean project with identical geometry, mesh and trial-mode count.",force=True)
                self._last_mode_diagnostics = {}
                candidates = self._mode_candidates(
                    geometry, wavelength_m, include_upper=include_upper, include_lower=include_lower,
                    mesh_accuracy=mesh_accuracy, mesh_cells_override=mesh_cells_override,
                )
                if candidates:
                    if recovered_from_zero:
                        self._record_mode_issue(geometry,wavelength_m,include_upper,include_lower,cells,
                                                "recovered_after_zero_modes",attempt+1)
                    break
                recovered_from_zero = True
                self._record_mode_issue(geometry,wavelength_m,include_upper,include_lower,cells,"zero_modes",attempt+1)
            if not candidates:
                guide = "coupled" if include_upper and include_lower else "upper" if include_upper else "lower"
                location = " See fde_mode_diagnostics.json in this command's output directory." if self.progress else ""
                raise InvalidModeError(f"FDE returned no modes for the {guide} guide at {wavelength_m*1e9:.6g} nm "
                    f"after {self.config.solver.zero_mode_retries+1} fresh attempt(s); "
                    f"solver=2D Z normal, mesh={cells[0]}x{cells[1]}, "
                    f"lower width={geometry.w2_m*1e6:.6g} um. No empty result was cached."+location)
            if self.cache and use_cache:
                self.cache.put(key, candidates, kind="raw_modes")
        limit = self.config.solver.raw_cache_memory_entries
        if use_cache and limit:
            self._raw_memory[key] = candidates
            while len(self._raw_memory) > limit:
                self._raw_memory.popitem(last=False)
        return candidates

    def _record_mode_issue(self,geometry,wavelength_m,include_upper,include_lower,cells,status,attempt):
        """Keep zero-mode/field-transfer evidence separate from infeasibility."""
        entry = {"status":status,"attempt":attempt,"wavelength_m":float(wavelength_m),
                 "include_upper":include_upper,"include_lower":include_lower,
                 "solver_type":"2D Z normal","search":"near n","use_max_index":True,
                 "trial_modes":self.config.solver.number_of_trial_modes,"mesh_cells":list(cells),
                 "domain_m":[self.x_span_m,self.y_min_m,self.y_max_m],"geometry":asdict(geometry),
                 "active_rectangles":[asdict(r) for r in self._active_rectangles(geometry,include_upper,include_lower)],
                 "mode_data":dict(getattr(self,"_last_mode_diagnostics",{}))}
        self.last_mode_issue = entry
        if self.progress:
            path = self.progress.output_dir/"fde_mode_diagnostics.json"
            run_id = self.progress.run_id
            previous = {"run_id":run_id,"attempts":[]}
            if path.exists():
                try:
                    saved = json.loads(path.read_text(encoding="utf-8"))
                    if saved.get("run_id")==run_id: previous = saved
                except (ValueError,OSError): pass
            previous["attempts"] = (previous["attempts"]+[entry])[-64:]
            temporary = path.with_suffix('.json.tmp')
            temporary.write_text(json.dumps(previous,indent=2,allow_nan=False)+'\n',encoding='utf-8')
            temporary.replace(path)
            self.progress.checkpoint("fde_mode_diagnostics",entry)

    def _mode_candidates(self, geometry, wavelength_m, *, include_upper, include_lower,
                         mesh_accuracy=None, mesh_cells_override=None):
        """Update a persistent layout, solve, and transfer raw modes in one batch."""
        signature = stable_key(self._material_signature())
        profile = self._numerical_profile()
        ready = (getattr(self, "_project_ready", False)
                 and getattr(self, "_project_signature", None) == signature
                 and self.config.solver.reuse_mode_project)
        if profile is not None and (profile.local_dx_m or profile.local_dy_m):
            ready = False
        with self._timed("geometry_setup"):
            if not ready:
                self.session.eval("newproject;")
                self._installed_material_names = set()
            else:
                self.session.eval("switchtolayout;")
        liquid = self._install_materials(geometry.liquid_index) or "Liquid"
        rectangles = rectangles_for_cross_section(
            geometry, x_span_m=self.x_span_m, y_min_m=self.y_min_m, y_max_m=self.y_max_m,
        )
        names = tuple(r.name for r in rectangles)
        # A zero/nonzero slab transition changes layout topology. Keep materials,
        # rebuild layout objects only, then resume incremental updates.
        rebuild = not ready or names != getattr(self, "_layout_names", ())
        lines = ["selectall; delete;"] if ready and rebuild else []
        for rect in rectangles:
            mat = liquid if rect.material == "Liquid" else rect.material
            enabled = not ((rect.name.startswith("lower_") and not include_lower)
                           or (rect.name in {"upper_slab", "upper_ridge"} and not include_upper))
            if rebuild:
                lines.append(f'addrect; set("name","{rect.name}");')
            # Layout updates are always made in layout mode, outside analysis groups.
            for prop, value in (("material", f'"{mat}"'), ("x", f"{rect.x_center_m:.15g}"),
                                ("y", f"{rect.y_center_m:.15g}"), ("x span", f"{rect.x_span_m:.15g}"),
                                ("y span", f"{rect.y_span_m:.15g}"), ("enabled", str(int(enabled)))):
                lines.append(f'setnamed("{rect.name}","{prop}",{value});')
        if rebuild:
            lines.append("addfde;")
        else:
            # Use the default FDE name; do not rename the solver object.
            lines.append('select("FDE");')
        cells = self._mesh_cell_counts(mesh_accuracy) if mesh_cells_override is None else mesh_cells_override
        lines.extend([
            'set("solver type",3); set("z",0);',
            f'set("x",0); set("x span",{self.x_span_m:.15g});',
            f'set("y",{(self.y_min_m+self.y_max_m)/2:.15g}); set("y span",{self.y_max_m-self.y_min_m:.15g});',
            f'set("mesh cells x",{cells[0]}); set("mesh cells y",{cells[1]});',
            'set("x min bc","PML"); set("x max bc","PML"); set("y min bc","PML"); set("y max bc","PML");',
            f'setanalysis("wavelength",{wavelength_m:.15g});',
            f'setanalysis("number of trial modes",{self.config.solver.number_of_trial_modes});',
            'setanalysis("search","near n"); setanalysis("use max index",1);',
        ])
        if profile is not None:
            from .block0 import mesh_override_script
            lines += [f'set("pml layers",{profile.pml_layers});',
                      'vlac_fde_properties=get;',
                      'if (findstring(vlac_fde_properties,"autoscale pml parameters")!=-1) { set("autoscale pml parameters",1); }']
            lines += mesh_override_script(profile, geometry, include_upper, include_lower)
        script = "\n".join(lines)
        debug = os.environ.get("VLAC_DUMP_FDE_SCRIPT")
        if debug:
            path = Path(debug).expanduser()
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(script + "\nfindmodes;\n", encoding="utf-8")
        with self._timed("geometry_setup"):
            self.session.eval(script)
        self._project_ready, self._project_signature, self._layout_names = True, signature, names
        self._budget().check(1)
        self._budget().consume(1)
        token = self.progress.solver_started() if self.progress else None
        try:
            with self._timed("eigensolve"):
                self.session.eval("findmodes;")
        except Exception as exc:
            if self.progress:
                self.progress.solver_finished(token, error=str(exc))
            raise
        else:
            if self.progress:
                self.progress.solver_finished(token)
        with self._timed("field_transfer"):
            if self.config.solver.batch_mode_data:
                self.session.eval('''
vlac_mode_count=nummodes;
vlac_mode_data=struct;
vlac_mode_data.count=vlac_mode_count;
vlac_mode_data.cards=cell(1);
if(vlac_mode_count>0) {
vlac_cards=cell(vlac_mode_count);
for(vlac_i=1:vlac_mode_count) {
  vlac_card="mode"+num2str(vlac_i);
  vlac_item=struct;
  vlac_item.neff=getdata(vlac_card,"neff");
  vlac_item.x=getdata(vlac_card,"x"); vlac_item.y=getdata(vlac_card,"y");
  vlac_item.Ex=getdata(vlac_card,"Ex"); vlac_item.Ey=getdata(vlac_card,"Ey");
  vlac_cards{vlac_i}=vlac_item;
}
vlac_mode_data.cards=vlac_cards;
}
''')
                payload = self.session.getv("vlac_mode_data")
                count = int(np.asarray(payload["count"]).squeeze())
                raw = [] if count == 0 else payload["cards"]
                if isinstance(raw, dict):
                    raw = [raw]
                raw = list(raw)
                if count==0:
                    direct_count = int(np.asarray(self.session.nummodes()).squeeze())
                    if direct_count>0:
                        count = direct_count
                        raw = [{key:self.session.getdata(f"mode{i}",key)
                                for key in ("neff","x","y","Ex","Ey")} for i in range(1,count+1)]
            else:
                count = int(np.asarray(self.session.nummodes()).squeeze())
                raw = [{key: self.session.getdata(f"mode{i}", key)
                        for key in ("neff", "x", "y", "Ex", "Ey")} for i in range(1, count+1)]
        self._last_mode_diagnostics = {"mode_list_count":count,"transferred_cards":len(raw),"discarded_field_cards":[],"discarded_field_details":[]}
        if count!=len(raw):
            cells = self._mesh_cell_counts(mesh_accuracy) if mesh_cells_override is None else mesh_cells_override
            self._record_mode_issue(geometry,wavelength_m,include_upper,include_lower,cells,"mode_transfer_count_mismatch",1)
            raise RuntimeError("FDE mode count and transferred card count disagree; inspect fde_mode_diagnostics.json.")
        candidates = []
        with self._timed("field_processing"):
            for index, item in enumerate(raw, 1):
                neff = self._scalar_complex(item["neff"])
                ex = self._to_common_grid(item["x"], item["y"], item["Ex"])
                ey = self._to_common_grid(item["x"], item["y"], item["Ey"])
                norm = float(np.sqrt(np.sum(np.abs(ex)**2 + np.abs(ey)**2)))
                if not np.isfinite(norm) or norm <= 0:
                    self._last_mode_diagnostics["discarded_field_cards"].append(index)
                    def finite_or_none(value):
                        value = float(value)
                        return value if np.isfinite(value) else None
                    self._last_mode_diagnostics["discarded_field_details"].append({
                        "mode_number":index,"neff_real":finite_or_none(neff.real),"neff_imag":finite_or_none(neff.imag),
                        "native_x_bounds_m":[finite_or_none(np.min(item["x"])),finite_or_none(np.max(item["x"]))],
                        "native_y_bounds_m":[finite_or_none(np.min(item["y"])),finite_or_none(np.max(item["y"]))],
                        "native_field_shape":list(np.asarray(item["Ex"]).shape),
                        "native_ex_peak":finite_or_none(np.max(np.abs(item["Ex"]))),
                        "native_ey_peak":finite_or_none(np.max(np.abs(item["Ey"]))),
                        "interpolated_transverse_norm":finite_or_none(norm)})
                    continue
                ex, ey = ex/norm, ey/norm
                te_fraction = float(np.sum(np.abs(ex)**2))
                possible = [self._core_fraction(ex, ey, geometry, guide) for guide, active in
                            (("upper", include_upper), ("lower", include_lower)) if active]
                candidates.append(ModeSnapshot(neff, ex, ey, te_fraction, max(possible, default=0.),
                                               f"mode{index}@{neff.real:.9f}"))
        self._last_mode_diagnostics["usable_candidates"] = len(candidates)
        if count>0 and not candidates:
            cells = self._mesh_cell_counts(mesh_accuracy) if mesh_cells_override is None else mesh_cells_override
            self._record_mode_issue(geometry,wavelength_m,include_upper,include_lower,cells,"all_transferred_fields_unusable",1)
            raise RuntimeError("MODE found eigenmodes, but every transferred transverse field was zero or non-finite. "
                               "This is a field-transfer/processing failure, not a no-mode result. Inspect fde_mode_diagnostics.json.")
        return candidates

    def solve_isolated_mode(
        self,
        geometry: CrossSectionGeometry,
        wavelength_m: float,
        *,
        guide: str,
        reference: ModeSnapshot | None = None,
        compact_x: bool | None = None,
        mesh_accuracy: int | None = None,
        use_cache: bool = True,
    ) -> tuple[ModeSnapshot, float]:
        """Solve and overlap-track one uncoupled guide mode.

        For endpoint detuning, the guide can be translated to x=0 and solved
        in a narrower x-domain. The y-domain and all horizontal material
        interfaces remain unchanged. Raw mode candidates are cached separately
        from branch selection, so changing the overlap reference does not cause
        another MODE ``findmodes`` call.

        ``compact_x=False`` retains the original full-domain placement and is
        used by the FDE validation comparison. Coupled-mode coefficient
        extraction continues to use ``solve_bare_modes`` and the full domain.
        ``use_cache=False`` forces a fresh FDE solve for final PSO verification.
        """
        if guide not in {"upper", "lower"}:
            raise ValueError("guide must be 'upper' or 'lower'.")
        compact = (
            self.config.solver.endpoint_compact_x
            if compact_x is None
            else bool(compact_x)
        )
        if compact:
            centered_geometry = replace(geometry, d_c2c_m=0.0)
            domain_info = self.endpoint_isolated_domain_info(
                compact_x=True, mesh_accuracy=mesh_accuracy
            )
            x_span_m = domain_info["x_span_m"]
            y_min_m = domain_info["y_min_m"]
            y_max_m = domain_info["y_max_m"]
            mesh_cells = (
                domain_info["mesh_cells_x"],
                domain_info["mesh_cells_y"],
            )
        else:
            centered_geometry = geometry
            domain_info = self.endpoint_isolated_domain_info(
                compact_x=False, mesh_accuracy=mesh_accuracy
            )
            x_span_m = self.x_span_m
            y_min_m = self.y_min_m
            y_max_m = self.y_max_m
            mesh_cells = self._mesh_cell_counts(mesh_accuracy)

        if compact:
            from .block0 import certified_profile
            with self._temporary_domain(x_span_m=x_span_m, y_min_m=y_min_m, y_max_m=y_max_m,
                                        profile=certified_profile(self.config, 'isolated')):
                candidates = self._raw_mode_candidates(
                    centered_geometry, wavelength_m, include_upper=guide == "upper", include_lower=guide == "lower",
                    mesh_accuracy=mesh_accuracy, mesh_cells_override=mesh_cells, use_cache=use_cache,
                )
        else:
            candidates = self._raw_mode_candidates(
                centered_geometry, wavelength_m, include_upper=guide == "upper", include_lower=guide == "lower",
                mesh_accuracy=mesh_accuracy, mesh_cells_override=mesh_cells, use_cache=use_cache,
            )

        previous = (
            ()
            if reference is None
            else (BareModeReference(reference, reference),)
        )
        selected, overlap = select_mode(
            candidates,
            previous=previous,
            guide=guide,
            minimum_te_fraction=self.config.solver.minimum_te_fraction,
        )
        return selected, overlap

